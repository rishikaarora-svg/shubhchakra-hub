import { createContext, useCallback, useContext, useEffect, useMemo, useReducer, useRef } from 'react'
import { BINS, CODE_TO_STREAM, FOOD_CATEGORIES, EC_FINE_AVOIDED, FOOD_SLA_MS, KG_PER_MEAL, STREAMS, STREAM_KEYS, TRANSIT_MS, VARIANCE_LIMIT, VENUE, bagKg, targetsFor } from './streams.js'
import { translate } from './i18n.js'

/*
 Bag lifecycle (chain of custody):
   tagged → in_transit → arrived → accepted (NGO, food)            ✓ diverted
                                 → verified (facility, ±5% mass)     ✓ diverted (sanitary = safely incinerated, not diverted)
                                 → flagged  (facility, >5% variance)
   food: in_transit/arrived + NGO reject or SLA breach → rerouted (in_transit to compost MRF)
*/

const STORAGE_KEY = 'shubhchakra-hub-state-v5'
const MIN = 60 * 1000

export const nextBagId = (state, stream) => `${STREAMS[stream].code}-${state.seq[stream]}`

function seedState() {
  const now = Date.now()
  const t = (m) => now - m * MIN
  const seed = (id, bin, qty, declaredKg, status, minsAgo, facilityKg = null) => {
    const stream = CODE_TO_STREAM[id.slice(0, 2)]
    const closed = status === 'accepted' || status === 'verified'
    const history = [{ at: t(minsAgo + 25), msg: 'QR tag generated by Field Coordinator' }]
    if (status !== 'tagged') history.push({ at: t(minsAgo + (closed ? 20 : 0)), msg: 'Dispatched from venue' })
    if (closed) history.push({ at: t(minsAgo), msg: status === 'accepted' ? 'Received by NGO' : `Verified on facility weighbridge at ${facilityKg} kg` })
    return {
      id, stream, bin, qty, declaredKg, facilityKg, seed: true,
      variance: facilityKg != null ? (facilityKg - declaredKg) / declaredKg : null,
      destination: stream === 'food' ? 'ngo' : 'recycler',
      status, createdAt: t(minsAgo + 25),
      dispatchedAt: status === 'tagged' ? null : t(minsAgo + (closed ? 20 : 0)),
      closedAt: closed ? t(minsAgo) : null,
      slaDeadline: stream === 'food' && !closed && status !== 'tagged' ? t(minsAgo) + FOOD_SLA_MS : null,
      ai: { source: 'gemini', confidence: 0.93, stream },
      history,
    }
  }
  return {
    lang: 'en',
    event: {
      venue: VENUE.name, name: VENUE.event, guests: 500, menu: 'buffet', start: '19:00', end: '01:00', autoIntimation: true,
      registered: false, cpcbId: null, registeredAt: null,
    },
    // newest first; opening numbers: 225.3 / 240 kg diverted (93.9%), 150 meals, 201.6 kg CO2e
    bags: [
      { ...seed('FR-1042', 'crate', 1, 15, 'tagged', 3), foods: [{ name: 'Paneer butter masala', type: 'veg', category: 'cooked' }, { name: 'Jeera rice', type: 'veg', category: 'cooked' }] },
      seed('DR-3012', 'crate', 1, 15, 'in_transit', 6),
      seed('OR-2032', 'crate', 2, 30, 'verified', 40, 30.3),
      { ...seed('FR-1041', 'drum', 1, 40, 'accepted', 55), foods: [{ name: 'Dal makhani', type: 'veg', category: 'cooked' }, { name: 'Butter naan', type: 'veg', category: 'cooked' }] },
      { ...seed('FR-1039', 'drum', 1, 35, 'accepted', 70), foods: [{ name: 'Veg biryani', type: 'veg', category: 'cooked' }, { name: 'Mixed raita', type: 'veg', category: 'cooked' }, { name: 'Gulab jamun', type: 'veg', category: 'sweet' }] },
      seed('SN-4005', 'crate', 1, 15, 'verified', 85, 14.7),
      seed('DR-3011', 'drum', 1, 40, 'verified', 95, 40.8),
      seed('OR-2031', 'bin', 1, 80, 'verified', 110, 79.2),
    ],
    seq: Object.fromEntries(STREAM_KEYS.map((k) => [k, STREAMS[k].firstSeq])),
    log: [{ at: now, kind: 'info', msg: 'Earlier batches closed. Ready for live service.' }],
  }
}

function load() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (raw) return JSON.parse(raw)
  } catch { /* storage unavailable */ }
  return seedState()
}

const addLog = (state, at, msg, kind = 'info') => ({ ...state, log: [{ at, msg, kind }, ...state.log].slice(0, 60) })
const patchBag = (state, id, fn) => ({ ...state, bags: state.bags.map((b) => (b.id === id ? fn(b) : b)) })
const hist = (b, at, msg) => [...b.history, { at, msg }]

function reducer(state, a) {
  const at = a.now
  switch (a.type) {
    case 'HYDRATE':
      return a.state
    case 'RESET':
      return { ...seedState(), lang: state.lang }
    case 'SET_LANG':
      return { ...state, lang: a.lang }
    case 'SET_EVENT':
      if (state.event.registered) return state
      return { ...state, event: { ...state.event, ...a.patch } }
    case 'REGISTER_EVENT':
      return addLog({ ...state, event: { ...state.event, registered: true, cpcbId: 'CPCB-BWG-2026-JPR-8842', registeredAt: at } }, at,
        `${state.event.name} registered at ${state.event.venue} for ${state.event.guests} guests. CPCB event ID CPCB-BWG-2026-JPR-8842${state.event.autoIntimation ? ', 3-day municipal intimation filed' : ''}`, 'success')
    case 'CREATE_BAG': {
      const id = nextBagId(state, a.bag.stream)
      const bag = {
        ...a.bag, id, status: 'tagged', createdAt: at,
        destination: a.bag.stream === 'food' ? 'ngo' : 'recycler',
        history: [{ at, msg: `QR tag generated: ${a.bag.qty} × ${a.bag.bin}, ${a.bag.declaredKg} kg declared` }],
      }
      return addLog({ ...state, bags: [bag, ...state.bags], seq: { ...state.seq, [bag.stream]: state.seq[bag.stream] + 1 } }, at,
        `${id} tagged (${STREAMS[bag.stream].label.en}, ${bag.declaredKg} kg)`)
    }
    case 'IMPORT_BAG': // QR scanned on a device that has never seen this bag (cross-device deep link)
      if (state.bags.some((b) => b.id === a.bag.id)) return state
      return addLog({ ...state, bags: [a.bag, ...state.bags] }, at, `${a.bag.id} loaded from scanned QR code`)
    case 'DISPATCH': {
      const s = patchBag(state, a.id, (b) => ({
        ...b, status: 'in_transit', dispatchedAt: at,
        slaDeadline: b.stream === 'food' ? at + FOOD_SLA_MS : null,
        history: hist(b, at, b.stream === 'food' ? 'Dispatched to NGO, 2-hour FSSAI window started' : 'Dispatched to facility'),
      }))
      return addLog(s, at, `${a.id} dispatched`)
    }
    case 'ARRIVE':
      return addLog(patchBag(state, a.id, (b) => ({ ...b, status: 'arrived', arrivedAt: at, history: hist(b, at, 'Vehicle arrived at destination') })), at, `${a.id} arrived at destination`)
    case 'NGO_ACCEPT': {
      const kg = state.bags.find((b) => b.id === a.id)?.declaredKg || 0
      return addLog(patchBag(state, a.id, (b) => ({ ...b, status: 'accepted', closedAt: at, history: hist(b, at, 'Received by NGO, responsibility closed') })), at,
        `${a.id} received by NGO: ${Math.round(kg / KG_PER_MEAL)} meals rescued`, 'success')
    }
    case 'REROUTE':
      return addLog(patchBag(state, a.id, (b) => ({
        ...b, status: 'in_transit', destination: 'recycler', rerouted: true, rerouteReason: a.reason, dispatchedAt: at, arrivedAt: null, slaDeadline: null,
        history: hist(b, at, `Rerouted to composting: ${a.reason}`),
      })), at, `${a.id} rerouted to Langariyawas MRF for composting (${a.reason})`, 'warn')
    case 'REQUEST_PROOF':
      return addLog(patchBag(state, a.id, (b) => ({ ...b, proof: { requestedAt: at }, history: hist(b, at, 'Control Tower requested a live photo') })), at, `Photo proof requested from NGO for ${a.id}`, 'warn')
    case 'FULFILL_PROOF':
      return addLog(patchBag(state, a.id, (b) => ({ ...b, proof: { ...b.proof, fulfilledAt: at, photo: a.photo }, history: hist(b, at, 'NGO sent photo proof') })), at, `NGO photo proof received for ${a.id}`, 'success')
    case 'GATE_VERIFY': {
      const s = patchBag(state, a.id, (b) => {
        const variance = (a.facilityKg - b.declaredKg) / b.declaredKg
        const ok = Math.abs(variance) <= VARIANCE_LIMIT
        return {
          ...b, status: ok ? 'verified' : 'flagged', facilityKg: a.facilityKg, variance, arrivalPhoto: a.photo || b.arrivalPhoto, closedAt: at,
          history: hist(b, at, `Weighbridge ${a.facilityKg} kg (${(variance * 100).toFixed(1)}% difference): ${ok ? 'verified' : 'flagged for audit'}`),
        }
      })
      const b = s.bags.find((x) => x.id === a.id)
      return addLog(s, at, `${a.id} ${b.status === 'verified' ? 'verified' : 'flagged'} at facility (${a.facilityKg} kg)`, b.status === 'verified' ? 'success' : 'error')
    }
    case 'FAST_FORWARD': {
      // Demo shortcut: ages every bag that is on the move instead of moving the clock,
      // so activity times always show the real time.
      const moving = (b) => ['in_transit', 'arrived'].includes(b.status)
      const shift = (v) => (v == null ? v : v - a.ms)
      const count = state.bags.filter(moving).length
      const bags = state.bags.map((b) => (moving(b) ? { ...b, dispatchedAt: shift(b.dispatchedAt), arrivedAt: shift(b.arrivedAt), slaDeadline: shift(b.slaDeadline) } : b))
      return addLog({ ...state, bags }, at, `Skipped ${Math.round(a.ms / MIN)} minutes ahead for ${count} bag${count === 1 ? '' : 's'} on the move`)
    }
    case 'TICK': {
      let s = state
      for (const b of state.bags) {
        if (b.status === 'in_transit' && at - b.dispatchedAt >= TRANSIT_MS) s = reducer(s, { type: 'ARRIVE', id: b.id, now: at })
        const cur = s.bags.find((x) => x.id === b.id)
        if (cur.stream === 'food' && cur.destination === 'ngo' && ['in_transit', 'arrived'].includes(cur.status) && cur.slaDeadline && at > cur.slaDeadline) {
          s = reducer(s, { type: 'REROUTE', id: b.id, now: at, reason: '2-hour FSSAI window passed' })
        }
      }
      return s
    }
    default:
      return state
  }
}

export const finalStream = (b) => (b.rerouted ? 'organic' : b.stream)

export function computeMetrics(state) {
  const bags = state.bags
  const isDiverted = (b) => b.status === 'accepted' || (b.status === 'verified' && b.stream !== 'sanitary')
  const isClosed = (b) => ['accepted', 'verified', 'flagged'].includes(b.status)
  const diverted = bags.filter(isDiverted).reduce((s, b) => s + bagKg(b), 0)
  const closed = bags.filter(isClosed).reduce((s, b) => s + bagKg(b), 0)
  const generated = bags.reduce((s, b) => s + bagKg(b), 0)
  const targets = targetsFor(state.event.guests, state.event.menu)
  const targetTotal = Object.values(targets).reduce((a, b) => a + b, 0)
  const base = Math.max(targetTotal, closed) // grows if the event produces more than estimated
  const byStream = Object.fromEntries(STREAM_KEYS.map((k) => [k, bags.filter((b) => finalStream(b) === k).reduce((s, b) => s + bagKg(b), 0)]))
  const divertedByStream = Object.fromEntries(STREAM_KEYS.map((k) => [k, bags.filter((b) => isDiverted(b) && finalStream(b) === k).reduce((s, b) => s + bagKg(b), 0)]))
  const rescuedFood = bags.filter((b) => b.stream === 'food' && b.status === 'accepted').reduce((s, b) => s + b.declaredKg, 0)
  const co2 = bags.filter(isDiverted).reduce((s, b) => s + bagKg(b) * STREAMS[finalStream(b)].co2PerKg, 0)
  const pct = base ? (diverted / base) * 100 : 0
  const flagged = bags.filter((b) => b.status === 'flagged').length
  const compliant = pct >= 80 && flagged === 0
  return {
    generated, diverted, base, pct, byStream, divertedByStream, rescuedFood, flagged, compliant, targets, targetTotal,
    meals: Math.round(rescuedFood / KG_PER_MEAL),
    co2: Math.round(co2 * 10) / 10,
    ecAvoided: compliant ? EC_FINE_AVOIDED : 0,
    open: bags.filter((b) => ['tagged', 'in_transit', 'arrived'].includes(b.status)).length,
  }
}

const Ctx = createContext(null)

export function StoreProvider({ children }) {
  const [state, rawDispatch] = useReducer(reducer, undefined, load)
  const stateRef = useRef(state)
  stateRef.current = state
  const now = useCallback(() => Date.now(), [])
  const dispatch = useCallback((a) => rawDispatch({ now: Date.now(), ...a }), [])

  // persist + cross-tab sync (a phone-sized tab and a projector tab share one live demo)
  const fromStorage = useRef(false)
  useEffect(() => {
    if (fromStorage.current) { fromStorage.current = false; return }
    try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)) } catch { /* quota / private mode */ }
  }, [state])
  useEffect(() => {
    const onStorage = (e) => {
      if (e.key !== STORAGE_KEY || !e.newValue) return
      try { fromStorage.current = true; rawDispatch({ type: 'HYDRATE', state: JSON.parse(e.newValue) }) } catch { /* ignore */ }
    }
    window.addEventListener('storage', onStorage)
    return () => window.removeEventListener('storage', onStorage)
  }, [])

  // time-driven transitions (transit arrival, SLA fallback)
  useEffect(() => {
    const id = setInterval(() => rawDispatch({ type: 'TICK', now: Date.now() }), 1000)
    return () => clearInterval(id)
  }, [])

  const metrics = useMemo(() => computeMetrics(state), [state])
  const t = useCallback((key) => translate(state.lang, key), [state.lang])
  const value = useMemo(() => ({ state, dispatch, metrics, t, now, lang: state.lang }), [state, dispatch, metrics, t, now])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export const useStore = () => useContext(Ctx)

export function bagQrUrl(bag) {
  const role = bag.destination === 'ngo' ? 'ngo' : 'recycler'
  const p = new URLSearchParams({ role, bagId: bag.id, s: bag.stream, kg: String(bag.declaredKg), b: bag.bin, q: String(bag.qty) })
  // dishes travel in the QR so a phone that has never seen this bag still knows the food (V:/N:/U: = veg / non-veg / unknown)
  if (bag.foods?.length) p.set('f', bag.foods.map((f) => `${f.type === 'veg' ? 'V' : f.type === 'non-veg' ? 'N' : 'U'}:${f.category || 'other'}:${f.name}`).join('|'))
  return `${window.location.origin}${window.location.pathname}?${p}`
}

const ID_RE = /\b(FR|OR|DR|SN)-\d{4}\b/

// Parse either a full deep-link URL or a raw bag ID from a scanned QR.
export function parseQrPayload(text) {
  const raw = String(text || '').trim()
  try {
    const u = new URL(raw)
    const p = u.searchParams
    const id = p.get('bagId')?.toUpperCase()
    const foods = (p.get('f') || '').split('|').filter(Boolean).map((x) => {
      const [t, ...rest] = x.split(':')
      const hasCat = rest.length > 1 && FOOD_CATEGORIES.some((c) => c.key === rest[0])
      return { type: { V: 'veg', N: 'non-veg' }[t] || 'unknown', category: hasCat ? rest[0] : 'other', name: (hasCat ? rest.slice(1) : rest).join(':'), rescuable: true }
    })
    if (id && ID_RE.test(id)) return { id, stream: p.get('s'), kg: Number(p.get('kg')) || null, bin: p.get('b'), qty: Number(p.get('q')) || 1, role: p.get('role'), foods }
  } catch { /* not a URL */ }
  const m = raw.toUpperCase().match(ID_RE)
  return m ? { id: m[0] } : null
}

export function bagFromPayload(p, at) {
  const stream = STREAMS[p.stream] ? p.stream : CODE_TO_STREAM[p.id.slice(0, 2)] || 'dry'
  const declaredKg = p.kg || BINS.find((b) => b.key === p.bin)?.kg || 40
  return {
    id: p.id, stream, bin: p.bin || 'drum', qty: p.qty || 1, declaredKg, foods: p.foods || [],
    destination: p.role === 'ngo' || (stream === 'food' && p.role !== 'recycler') ? 'ngo' : 'recycler',
    status: 'arrived', createdAt: at, dispatchedAt: at, arrivedAt: at,
    slaDeadline: stream === 'food' ? at + FOOD_SLA_MS : null,
    imported: true,
    history: [{ at, msg: 'Bag record rebuilt from scanned QR code' }],
  }
}
